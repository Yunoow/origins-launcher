function isSupportedLanguage(code) {
    return ORIGINS_LANGUAGES.some((language) => language.code === code);
}

// Best match for the system language (fr-CA -> fr), English otherwise.
function detectSystemLanguage() {
    const candidates = [...(navigator.languages || []), navigator.language || ""];
    for (const candidate of candidates) {
        const code = String(candidate || "").slice(0, 2).toLowerCase();
        if (isSupportedLanguage(code)) return code;
    }
    return "en";
}

// t("key", { name: "Nyx" }) -> translated text for the current launcher
// language, falling back to English, then to the key itself.
function t(key, params = null) {
    const language =
        typeof currentLauncherLanguage === "string" ? currentLauncherLanguage : "en";
    let text = translations[language]?.[key] ?? translations.en[key] ?? key;
    if (params) {
        for (const [name, value] of Object.entries(params)) {
            text = text.split(`{${name}}`).join(String(value));
        }
    }
    return text;
}
